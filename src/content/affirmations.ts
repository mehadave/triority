/** Stable pick for a date key, so the line stays put all day. */
export function affirmationFor(dateKey: string): string {
  let hash = 0;
  for (const ch of dateKey) hash = (hash * 31 + ch.charCodeAt(0)) >>> 0;
  return AFFIRMATIONS[hash % AFFIRMATIONS.length]!;
}
